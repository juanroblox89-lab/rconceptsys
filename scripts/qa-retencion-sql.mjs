import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';

// PGlite local en memoria. No contiene el servicio HTTP de Storage ni pg_cron.
// Uso: node scripts/qa-retencion-sql.mjs <ruta-al-entrypoint-de-pglite>
assert.ok(process.argv[2], 'Indica el entrypoint local de PGlite');
const { PGlite } = await import(pathToFileURL(resolve(process.argv[2])).href);
const db = new PGlite();
const sql = readFileSync(new URL('../supabase/migrations/030_chat_whatsapp_y_retencion.sql', import.meta.url), 'utf8');
const eva = '00000000-0000-4000-8000-000000000001';
const lina = '00000000-0000-4000-8000-000000000002';
const intento = '00000000-0000-4000-8000-000000000003';
const idAsig = id => `00000000-0000-4000-8000-${String(id).padStart(12,'0')}`;
try {
  await db.exec(`
    create role anon; create role authenticated; create role service_role bypassrls;
    create schema storage; create schema vault; create schema net;
    create table storage.objects(bucket_id text, name text, primary key(bucket_id,name));
    create table vault.decrypted_secrets(name text,decrypted_secret text);
    create function net.http_get(url text, headers jsonb, timeout_milliseconds int) returns bigint language sql as $$ select 1::bigint $$;
    create function public.es_miembro() returns boolean language sql as $$ select true $$;
    create table public.perfiles(id uuid primary key,nombre text,estado text,es_admin boolean);
    create table public.chat_mensajes(id bigint generated by default as identity primary key, autor_id uuid references perfiles, cuerpo text, borrado_en timestamptz);
    create table public.chat_adjuntos(id bigint primary key, mensaje_id bigint references chat_mensajes, autor_id uuid references perfiles,
      tipo text, storage_path text, url_externa text, creado_en timestamptz);
    create table public.tareas(id bigint primary key, estado text,resuelta_en timestamptz, descripcion text, asignado_a uuid);
    create table public.asignacion_adjuntos(id uuid primary key,tarea_id bigint references tareas,tipo text,ruta text,
      estado_archivo text,creado_en timestamptz,resumir boolean,estado_resumen text,resumen_intento uuid,resumen_hasta timestamptz,
      actualizado_en timestamptz,resumen jsonb,transcripcion text);
    alter table public.chat_adjuntos enable row level security;
    alter table storage.objects enable row level security;
    grant select,insert,update on all tables in schema public to service_role;
  `);
  await db.exec(sql);
  await db.exec(sql);
  await db.exec(`
    insert into perfiles values ('${eva}','Eva','aprobado',false),('${lina}','Lina','aprobado',false);
    insert into chat_mensajes(autor_id,cuerpo) values ('${eva}','Original intacto');
    insert into chat_adjuntos (id,mensaje_id,autor_id,tipo,storage_path,url_externa,creado_en,conservar) values
      (1,1,'${eva}','audio','${eva}/1-voz.webm',null,now()-interval '16 days',false),
      (2,1,'${eva}','imagen','${eva}/2-foto.png',null,now()-interval '14 days',false),
      (3,1,'${eva}','video','${eva}/3-video.webm',null,now()-interval '16 days',true),
      (4,1,'${eva}','drive',null,'https://drive.google.com/drive/folders/demo',now()-interval '16 days',false),
      (5,1,'${eva}','audio','${eva}/5-externo.webm','https://drive.google.com/drive/folders/demo',now()-interval '16 days',false),
      (6,1,'${eva}','archivo','${eva}/6-doc.pdf',null,now()-interval '16 days',false),
      (7,null,'${lina}','audio','${lina}/7-nota.webm',null,now(),false),
      (8,1,'${eva}','audio','${eva}/8-igual.webm',null,now()-interval '16 days',false),
      (9,1,'${eva}','audio','${eva}/8-igual.webm',null,now()-interval '16 days',true);
    insert into storage.objects select 'chat',storage_path from chat_adjuntos where storage_path is not null on conflict do nothing;
    insert into tareas values
      (1,'aceptada',now()-interval '16 days','Aprobada','${eva}'),
      (2,'cancelada',now()-interval '16 days','Cancelada','${eva}'),
      (3,'pendiente',now()-interval '20 days','Abierta','${eva}'),
      (4,'hecha',now()-interval '20 days','En revisión','${eva}'),
      (5,'rechazada',now()-interval '20 days','Devuelta','${eva}'),
      (6,'aceptada',now()-interval '14 days','Cierre reciente','${eva}'),
      (7,'cancelada',null,'Sin cierre','${eva}'),
      (8,'aceptada',now()-interval '16 days','Protegida','${eva}'),
      (9,'aceptada',now()-interval '16 days','Subida reciente','${eva}'),
      (10,'aceptada',now()-interval '16 days','Resumen pendiente','${eva}');
    insert into asignacion_adjuntos(id,tarea_id,tipo,ruta,estado_archivo,creado_en,resumir,estado_resumen,resumen,transcripcion,conservar)
      select (a.id)::uuid,a.tarea,'audio',a.tarea||'/'||a.id||'/archivo','listo',now()-make_interval(days => case when tarea=9 then 14 else 16 end),
      true,case when tarea=10 then 'pendiente' else 'listo' end,'["Conservar el resumen"]','Transcripción intacta',tarea=8
      from (values ${Array.from({length:10},(_,i)=>`('${idAsig(i+1)}',${i+1})`).join(',')}) a(id,tarea);
    insert into storage.objects select 'asignaciones-adjuntos',ruta from asignacion_adjuntos;
    set role service_role;
  `);
  const q = async (s, p = []) => (await db.query(s,p)).rows;
  assert.deepEqual(await q('select rc_enviar_chat($1,$2,$3,$4) as id',[eva,'',1,[7]]),[{id:null}]);
  assert.deepEqual(await q('select rc_enviar_chat($1,$2,$3,$4) as id',[lina,'',1,[7]]),[{id:2}]);
  assert.deepEqual(await q('select respuesta_a_id,cuerpo from chat_mensajes order by id'),[{respuesta_a_id:null,cuerpo:'Original intacto'},{respuesta_a_id:1,cuerpo:''}]);
  assert.equal((await q('select id from rc_conservar_chat(2,$1,true)',[lina])).length,1);
  assert.equal((await q('select id from rc_conservar_chat(3,$1,false)',[lina])).length,0);
  assert.deepEqual(await q('select id from rc_reclamar_purga_chat($1)',[intento]),[{id:'1'}]);
  assert.deepEqual(await q('select id from rc_conservar_chat(1,$1,true)',[eva]),[]);
  assert.deepEqual(await q('select rc_marcar_purga($1,$2,$3) as marcado',['chat','1',intento]),[{marcado:false}]);
  await db.exec(`reset role; delete from storage.objects where name='${eva}/1-voz.webm'; set role service_role`);
  assert.deepEqual(await q('select rc_marcar_purga($1,$2,$3) as marcado',['chat','1',intento]),[{marcado:true}]);
  assert.deepEqual(await q('select id from rc_reclamar_purga_chat($1)',[intento]),[]);
  assert.deepEqual(await q('select id from chat_adjuntos where purgado_en is not null'),[{id:1}]);
  assert.deepEqual(await q('select id from rc_reclamar_purga_asignacion($1)',[intento]),[{id:idAsig(1)}]);
  await assert.rejects(db.exec("update tareas set estado='pendiente' where id=1"),/purga_en_curso/);
  for (const id of [1,2]) {
    if (id===2) assert.deepEqual(await q('select id from rc_reclamar_purga_asignacion($1)',[intento]),[{id:idAsig(id)}]);
    await db.exec(`reset role; delete from storage.objects where bucket_id='asignaciones-adjuntos' and name like '${id}/%'; set role service_role`);
    assert.deepEqual(await q('select rc_marcar_purga($1,$2,$3) as marcado',['asignaciones-adjuntos',idAsig(id),intento]),[{marcado:true}]);
  }
  assert.deepEqual(await q('select id from rc_reclamar_purga_asignacion($1)',[intento]),[]);
  assert.equal((await q("select id from asignacion_adjuntos where purgado_en is not null and transcripcion='Transcripción intacta' and resumen='[\"Conservar el resumen\"]'::jsonb")).length,2);
  await db.exec("update tareas set estado='pendiente' where id=1; reset role;");
  for (const rol of ['anon','authenticated']) {
    await db.exec(`set role ${rol}`);
    await assert.rejects(q('select id from rc_reclamar_purga_chat($1)',[intento]),/permission denied/);
    await assert.rejects(q('select rc_enviar_chat($1,$2,$3,$4)',[eva,'',1,[7]]),/permission denied/);
    await db.exec('reset role');
  }
  console.log('SQL OK: migración dos veces, límites, permisos, cita atómica, locks, orden y metadatos intactos.');
} finally { await db.close(); }
