import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { join } from 'node:path';

const docs = 'docs/ria';
const archivos = readdirSync(docs).filter(n => /^manual-.*\.md$/.test(n));
const manual = archivos.map(n => readFileSync(join(docs, n), 'utf8')).join('\n');
const sinDocumentar = [];
function revisarApp(carpeta, segmentos = []) {
  for (const e of readdirSync(carpeta, { withFileTypes: true })) {
    if (e.isDirectory()) revisarApp(join(carpeta, e.name), /^\(.+\)$/.test(e.name) ? segmentos : [...segmentos, e.name]);
    else if (/^(page|route)\.[jt]sx?$/.test(e.name)) {
      const ruta = '/' + segmentos.join('/');
      if (!manual.includes('`' + ruta + '`')) sinDocumentar.push(ruta);
    }
  }
}
revisarApp('app');
for (const f of readdirSync('backend/internal/httpapi').filter(n => n.endsWith('.go') && !n.endsWith('_test.go') && !n.endsWith('_gen.go'))) {
  for (const [, ruta] of readFileSync(join('backend/internal/httpapi', f), 'utf8').matchAll(/"((?:GET|POST|PATCH|PUT|DELETE) \/api\/admin\/[^"\n]+)"/g)) {
    if (!manual.includes('`' + ruta + '`')) sinDocumentar.push(ruta);
  }
}
const fuentes = { riaConocimiento: 'conocimiento.md', riaManualEquipo: 'manual-equipo.md', riaManualAdmin: 'manual-admin.md', riaManualEditor: 'manual-editor.md', riaManualCamara: 'manual-camarografo.md', riaManualSubidor: 'manual-subidor.md' };
const generado = '// Code generated by scripts/verificar-ria.mjs; DO NOT EDIT.\n\npackage httpapi\n\n' + Object.entries(fuentes).map(([k,v]) => `const ${k} = ${JSON.stringify(readFileSync(join(docs,v),'utf8').replaceAll('\r\n','\n'))}\n`).join('');
const destino = 'backend/internal/httpapi/ria_docs_gen.go';
if (sinDocumentar.length) { console.error('Falta documentar en docs/ria/:\n' + [...new Set(sinDocumentar)].join('\n')); process.exitCode = 1; }
if (process.argv.includes('--generar')) writeFileSync(destino, generado);
else if (readFileSync(destino, 'utf8').replaceAll('\r\n','\n') !== generado) { console.error('Actualiza el contexto compilado: node scripts/verificar-ria.mjs --generar'); process.exitCode = 1; }
